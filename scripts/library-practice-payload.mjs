// Store shared question text once; preserve all format IDs for saved history.
export function libraryPracticeModule(skills,exercises,listing){
 const skillIndexes=new Map(skills.map((s,i)=>[s.id,i])),groups=new Map();
 for(const e of exercises){
  const group=groups.get(e.sourceQuestionId)||[];group.push(e);groups.set(e.sourceQuestionId,group);
 }
 const rows=[...groups.values()].map(group=>{
  const e=group[0],mcq=group.find(e=>e.type==='mcq');
  return [e.sourceQuestionId,skillIndexes.get(e.skill),e.grades[0],e.prompt,e.answer,e.rule,e.level,group.map(e=>e.type==='mcq'?'m':'e').join(''),mcq?.choices??null,mcq?.correctIndex??null];
 });
 const indexes=new Map(exercises.map((e,i)=>[e.id,i]));
 return '// Generated by scripts/build-library-practice.mjs from verified DATATM questions only.\n'+
  'export const libraryPracticeSkills='+JSON.stringify(skills)+';\n'+
  'export const libraryPracticeExercises='+JSON.stringify(rows)+`.flatMap(([sourceQuestionId,s,grade,prompt,answer,rule,level,formats,choices,correctIndex])=>[...formats].map(format=>{
 const type=format==='m'?'mcq':'essay';
 return {id:'practice-'+sourceQuestionId+'-'+type,sourceQuestionId,libraryPractice:true,skill:libraryPracticeSkills[s].id,grades:[grade],type,prompt,richPrompt:true,answer,rule,...(type==='mcq'?{choices,correctIndex}:{}),keywords:[],level};
}));\n`+
  'export const libraryPracticeListedIds='+JSON.stringify(listing.ids.map(id=>indexes.get(id)))+'.map(i=>libraryPracticeExercises[i].id);\n'+
  'export const libraryPracticeSummary='+JSON.stringify(listing.summary)+';\n';
}
